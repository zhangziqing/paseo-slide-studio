// Bundle editor assets as data; installed plugins need no sibling checkout.
import { readFile, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';

const check = process.argv.includes('--check');
const editor = new URL('../editor/', import.meta.url);
const files = ['index.html', 'server.py', 'src/core.js', 'src/editor.js', 'src/editor.css', 'src/runtime.js', 'src/workspace.js'];
const assets = {};
for (const file of files) assets[file] = await readFile(new URL(file, editor), 'utf8');
assets['runner_rpc.py'] = await readFile(new URL('../server/runner_rpc.py', import.meta.url), 'utf8');
const serverModule =
  '// Generated by scripts/prepare.mjs from the existing HTML PPT editor.\n' +
  'export const editorAssets: Record<string, string> = ' + JSON.stringify({ 'server.py': assets['server.py'], 'runner_rpc.py': assets['runner_rpc.py'] }, null, 2) + ';\n';

const script = code => '<script>' + code.replace(/<\/script/gi, '<\\/script') + '</script>';
let editorScript = assets['src/editor.js'];
const pathLookup = "const path = new URL(location.href).searchParams.get('file');";
const historyUpdate = "history.replaceState(null, '', url);";
const saveStatus = "const dirty = this.diskDirty();";
const thumbnails = "const css = H.resourceCss([...this.deck.doc.querySelectorAll('style')].map(n => n.textContent).join('\\n'), this.deck.resourceBase);";
const editorCreated = 'const editor = new Editor(); window.pptEditor = editor;';
for (const anchor of [pathLookup, historyUpdate, saveStatus, thumbnails, editorCreated]) if (!editorScript.includes(anchor)) throw new Error('Editor integration anchor changed: ' + anchor);
editorScript = editorScript.replace(pathLookup, 'const path = this.workspace.initialPath;')
  .replace(historyUpdate, 'window.paseoEmbedded.updatePath(serverFile?.path ?? null);')
  .replace(saveStatus, saveStatus + '\n      window.paseoEmbedded.setModified(dirty);')
  .replace(thumbnails, 'const css = window.paseoEmbedded.thumbnailCss(this.deck);')
  .replace(editorCreated, editorCreated + '\n  window.paseoEmbedded.bindEditor(editor);')
  .replace("textContent = 'SERVER'", "textContent = 'PASEO'");
const extraCss = await readFile(new URL('./embedded.css', import.meta.url), 'utf8');
let embedded = assets['index.html'].replace('<link rel="stylesheet" href="src/editor.css">', '<style>' + assets['src/editor.css'] + '\n' + extraCss + '</style>');
const bridge = await readFile(new URL('./embedded.js', import.meta.url), 'utf8');
let scripts = '';
for (const file of ['runtime', 'core', 'workspace', 'editor']) {
  const code = file === 'workspace' ? bridge : file === 'editor' ? editorScript : assets['src/' + file + '.js'];
  embedded = embedded.replace('<script defer src="src/' + file + '.js"></script>', '');
  scripts += script(code);
}
// A function replacement preserves literal $& and $' in the editor's regex code.
embedded = embedded.replace('</body>', () => scripts + '</body>').replaceAll('服务器', '工作区');
for (const match of embedded.matchAll(/<script>([\s\S]*?)<\/script>/g)) new Script(match[1]);
const clientModule = '// Generated by scripts/prepare.mjs; the editor runs inside its Paseo panel.\nexport const editorDocument = ' + JSON.stringify(embedded) + ';\n';
for (const [path, content] of [['server/editor-assets.ts', serverModule], ['shared/editor-document.ts', clientModule]]) {
  const target = new URL('../' + path, import.meta.url);
  if (check) {
    if (await readFile(target, 'utf8') !== content) throw new Error(path + ' is stale; run npm run prepare:editor.');
  } else await writeFile(target, content);
}
console.error(check ? 'Bundled editor modules match their source.' : 'Bundled editor modules generated from editor/.');
